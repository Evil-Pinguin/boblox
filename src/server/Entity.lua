function Entity:tileCenter(gx, gy)
	local x, z = self.maze:tileToWorld(gx, gy, self.tile)
	return Vector3.new(x, 0, z)
end

function Entity:setPositionFromTile(gx, gy)
	self.tx, self.ty = gx, gy
	self.pos = self:tileCenter(gx, gy)
	self.nextTile = nil
	self.field = nil
	self.repathIn = 0
	self:applyCFrame(0)
end

--- Yaw that points the model's front (-Z) along self.dir.
function Entity:yaw()
	local d = self.dir
	if d.X == 0 and d.Z == 0 then
		return 0
	end
	return math.atan2(d.X, d.Z) + math.pi
end

function Entity:applyCFrame(bob)
	local model = self.model
	if not model or not model.PrimaryPart or not model.Parent then
		return
	end
	local lean = 0
	if self.state == "hunt" then
		lean = 8
	elseif self.state == "feeding" then
		lean = 14
	elseif self.state == "investigate" then
		lean = 3
	end
	local cf = CFrame.new(self.pos + Vector3.new(0, 3.4 + (bob or 0), 0))
		* CFrame.Angles(0, self:yaw(), 0)
		* CFrame.Angles(math.rad(lean * 0.35), 0, math.rad(lean * 0.12))
	model:PivotTo(cf)
end

--- A walkable cell tile at least `minTiles` (Chebyshev) from every live player.
function Entity:pickFarTile(minTiles, avoidTile)
	local tiles = {}
	local maze = self.maze
	for gy = 1, maze.gridH, 2 do
		for gx = 1, maze.gridW, 2 do
			tiles[#tiles + 1] = { gx, gy }
		end
	end
	if #tiles == 0 then
		return maze.entryX, maze.entryY
	end

	local best, bestScore
	for _ = 1, 80 do
		local cand = tiles[math.random(#tiles)]
		local gx, gy = cand[1], cand[2]
		local minDist = math.huge
		local valid = true

		if avoidTile then
			if math.max(math.abs(avoidTile[1] - gx), math.abs(avoidTile[2] - gy)) < 8 then
				valid = false
			end
		end

		if valid then
			for _, st in self.round:eachPlayer() do
				if st.joined and st.alive and not st.escaped then
					local d = math.max(math.abs(st.tx - gx), math.abs(st.ty - gy))
					if d < minTiles then
						valid = false
						break
					end
					if d < minDist then
						minDist = d
					end
				end
			end
		end

		if valid and (bestScore == nil or minDist > bestScore) then
			best, bestScore = cand, minDist
		end
	end

	if best then
		return best[1], best[2]
	end
	local fallback = tiles[math.random(#tiles)]
	return fallback[1], fallback[2]
end

--- Snap onto the grid when a tile is entered. Keeps the AI's tile bookkeeping exact
--  (it is the same grid the player's position is read from) with no visible hitch.
function Entity:snapToTile(gx, gy)
	self.tx, self.ty = gx, gy
	self.pos = self:tileCenter(gx, gy)
end

