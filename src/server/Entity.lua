local function limb(spec, parent, material, color, transparency)
	local part = Instance.new("Part")
	part.Name = spec.name
	part.Anchored = true
	part.CanCollide = false
	part.CanQuery = false
	part.CanTouch = false
	part.Massless = true
	part.Size = spec.size
	part.CFrame = CFrame.new(spec.pos)
	if spec.tilt then
		part.CFrame = part.CFrame * CFrame.Angles(0, 0, math.rad(spec.tilt))
	end
	part.Material = material
	part.Color = color
	part.Transparency = transparency
	part.CastShadow = true
	part.TopSurface = Enum.SurfaceType.Smooth
	part.BottomSurface = Enum.SurfaceType.Smooth
	if spec.ball then
		part.Shape = Enum.PartType.Ball
	end
	part.Parent = parent
	return part
end

function Entity:buildModel()
	local model = Instance.new("Model")
	model.Name = "TheHollow"

	self.parts = {}
	for _, spec in ipairs(BODY) do
		local part = limb(spec, model, Enum.Material.Fabric, cfg.BodyColor, cfg.FadeTransparency)
		self.parts[#self.parts + 1] = part
	end

	self.head = self.parts[2]

	self.glowParts = {}
	for _, spec in ipairs(GLOW) do
		local part = limb(spec, model, Enum.Material.Neon, cfg.EyeColor, 0.12)
		part.CastShadow = false
		self.glowParts[#self.glowParts + 1] = part
	end

	self.eyeLight = Instance.new("PointLight")
	self.eyeLight.Range = 21
	self.eyeLight.Brightness = 0.65
	self.eyeLight.Color = cfg.EyeColor
	self.eyeLight.Shadows = false
	self.eyeLight.Parent = self.head

	self.highlight = Instance.new("Highlight")
	self.highlight.Name = "Reveal"
	self.highlight.Adornee = model
	self.highlight.FillTransparency = 1
	self.highlight.OutlineTransparency = 1
	self.highlight.FillColor = Color3.fromRGB(158, 250, 236)
	self.highlight.OutlineColor = Color3.fromRGB(196, 62, 52)
	self.highlight.Parent = model

	model.PrimaryPart = self.parts[1]
	return model
end

--- deps = { round, level, root }
function Entity.new(deps)
	local self = setmetatable({}, Entity)
	self.round = deps.round
	self.level = deps.level
	self.maze = deps.level.maze
	self.tile = deps.level.tile
	self.parts = {}
	self.model = self:buildModel()
	self.model.Parent = deps.root

	self.state = "dormant"
	self.closestDist = math.huge
	self.target = nil
	self.pos = Vector3.new(0, 0, 0)
	self.tx, self.ty = deps.level.maze.entryX, deps.level.maze.entryY
	self.dir = Vector3.new(0, 0, -1)
	self.speed = 0
	self.time = 0
	self.walkPhase = 0
	self.targetPlayer = nil
	self.lastSeen = -1000
	self.lastKnown = nil
	self.investigateTile = nil
	self.investigateUntil = 0
	self.nextAttack = 0
	self.repathIn = 0
	self.field = nil
	self.fieldKey = nil
	self.nextTile = nil
	self.patrolTile = nil
	self.feedingUntil = 0
	self.revealedUntil = 0
	self.idleTime = 0
	self.aggro = 0
	self.revealed = false

	self.model:SetAttribute("State", self.state)
	self.model:SetAttribute("Revealed", false)
	return self
end

function Entity:destroy()
	if self.model then
		self.model:Destroy()
		self.model = nil
	end
	self.field = nil
	self.parts = {}
end

