--- Called at DecisionRate: perception, state machine, routing.
function Entity:tick(dt)
	self.time = self.time + dt
	local now = self.time

	self:computeDread()

	if self.state == "dormant" then
		self:updateReveal(now)
		return
	end

	if self.state == "feeding" then
		if now >= self.feedingUntil then
			self:setState("patrol")
			self.targetPlayer = nil
			self.lastKnown = nil
			self.patrolTile = nil
		end
		self:updateReveal(now)
		return
	end

	local target = self:scan()

	if target then
		if self.targetPlayer ~= target then
			self:setState("hunt")
		end
		self.targetPlayer = target
		self.lastSeen = now
		local st = self.round.players[target]
		if st then
			self.lastKnown = { st.tx, st.ty }
		end
		self.investigateTile = nil
	elseif self.state == "hunt" then
		if now - self.lastSeen > cfg.SightMemory then
			self:setState("investigate")
			self.investigateUntil = now + cfg.InvestigateTime
			self.investigateTile = self.lastKnown
		end
	elseif self.state == "investigate" then
		if now > self.investigateUntil then
			self:setState("patrol")
			self.patrolTile = nil
		end
	end

	self:repositionIfStuck(dt, target)
	self:plan()
	self:attackCheck(now)
	self:updateReveal(now)
end

--- Rebuild the flow field at most once per RepathInterval, never per frame.
function Entity:plan()
	local goal = self:goalTile()
	self.goal = goal

	if goal == nil then
		self.field = nil
		self.fieldKey = nil
		self.nextTile = nil
		return
	end

	local key = goal[1] .. "_" .. goal[2]
	self.repathIn = self.repathIn - DecisionRate

	if self.field == nil or self.fieldKey ~= key or self.repathIn <= 0 then
		self.field = self.maze:flowField(goal[1], goal[2])
		self.fieldKey = key
		self.repathIn = cfg.RepathInterval

		if self.field == nil or self.field[self.ty] == nil or self.field[self.ty][self.tx] == nil then
			-- Unreachable: stop shuffling at a wall, go and look instead.
			if self.state == "hunt" then
				self:setState("investigate")
				self.investigateUntil = self.time + cfg.InvestigateTime
			end
			self.field = nil
			self.nextTile = nil
			return
		end

		self.nextTile = self:stepFrom(self.tx, self.ty)
	end
end

--- Called every Heartbeat so the body glides instead of stepping tile to tile.
function Entity:advance(dt)
	if not self.model or not self.model.PrimaryPart then
		return
	end

	if self.state == "dormant" or self.state == "feeding" then
		self.speed = 0
		self:applyCFrame(math.sin(self.time * 0.9) * 0.06)
		return
	end

	if self.field == nil or self.nextTile == nil then
		self.speed = Util.lerp(self.speed, 0, 0.35)
		self:applyCFrame(math.sin(self.time * 2.2) * 0.07)
		self:keepInside()
		return
	end

	self:stepTowards(self.nextTile, dt)
	self:keepInside()
end

--- Hunting without a route for a while is the worst outcome for tension, so it
--- relocates rather than pacing a corner forever.
function Entity:repositionIfStuck(dt, target)
	if self.state == "hunt" and not target and self.targetPlayer then
		local st = self.round.players[self.targetPlayer]
		if st and st.hiddenLock then
			self.idleTime = 0
			return
		end
		self.idleTime = self.idleTime + dt
		if self.idleTime > cfg.TeleportCooldown then
			self.idleTime = 0
			self:reposition(16)
		end
	else
		self.idleTime = 0
	end
end

function Entity:currentSpeed()
	return (cfg.Speeds[self.state] or cfg.Speeds.patrol) + self.aggro
end

--- Where it wants to be, as a grid tile.
function Entity:goalTile()
	if self.state == "hunt" then
		if self.targetPlayer then
			local st = self.round.players[self.targetPlayer]
			if st and st.seen and not st.hiddenLock then
				return { st.tx, st.ty }
			end
		end
		return self.lastKnown
	elseif self.state == "investigate" then
		if self.investigateTile then
			return self.investigateTile
		end
		return self.lastKnown
	end

	local tile = self.patrolTile
	if tile == nil or (self.tx == tile[1] and self.ty == tile[2]) then
		local gx, gy
		if self.round.gateOpen and math.random() < 0.6 then
			-- the airlock is the only way out, and it knows that
			gx, gy = self.maze.entryX + 1, self.maze.entryY
		else
			gx, gy = self:pickFarTile(cfg.PatrolPickRadius, { self.tx, self.ty })
		end
		self.patrolTile = { gx, gy }
		tile = self.patrolTile
	end
	return tile
end

--- Next tile downhill, plus a tile of corner-cutting where the geometry allows it.
function Entity:stepFrom(fromX, fromY)
	local maze, field = self.maze, self.field
	local nx, ny = maze:descend(field, fromX, fromY)
	if nx == nil then
		return nil
	end

	local lx, ly = maze:descend(field, nx, ny)
	if lx then
		local target = self:tileCenter(lx, ly)
		local flatX, flatZ = target.X - self.pos.X, target.Z - self.pos.Z
		local length = math.sqrt(flatX * flatX + flatZ * flatZ)
		local samples = math.max(2, math.floor(length / (self.tile * 0.45)))
		local clear = true
		for i = 1, samples do
			local t = i / samples
			local tgx, tgy = maze:worldToTile(self.pos.X + flatX * t, self.pos.Z + flatZ * t, self.tile)
			if maze:isSolid(tgx, tgy) then
				clear = false
				break
			end
		end
		if clear then
			return { lx, ly }
		end
	end
	return { nx, ny }
end

function Entity:stepTowards(tile, dt)
	local goal = self:tileCenter(tile[1], tile[2])
	local toX, toZ = goal.X - self.pos.X, goal.Z - self.pos.Z
	local dist = math.sqrt(toX * toX + toZ * toZ)

	if dist > 0.001 then
		self.dir = Vector3.new(toX, 0, toZ).Unit
	end

	local speed = self:currentSpeed()
	self.speed = speed
	local step = math.min(speed * dt, dist)
	self.pos = self.pos + self.dir * step
	self.walkPhase = self.walkPhase + dt * (speed * 0.42 + 1.4)

	if dist - step <= 0.55 then
		-- Snap on arrival: the AI's tile bookkeeping stays exact, and half a stud of
		-- correction is invisible at these speeds.
		self:snapToTile(tile[1], tile[2])
		self.nextTile = self:stepFrom(self.tx, self.ty)
		self.repathIn = math.max(self.repathIn, 0.06)
		if self.nextTile == nil then
			self.field = nil
			self.fieldKey = nil
		end
	end

	local bob
	if self.state == "hunt" then
		bob = math.sin(self.walkPhase * 1.9) * 0.42
	else
		bob = math.sin(self.walkPhase * 0.55) * 0.1
	end
	self:applyCFrame(bob)
end

function Entity:attackCheck(now)
	if now < self.nextAttack then
		return
	end
	for player, st in self.round:eachPlayer() do
		if st.joined and st.alive and not st.escaped and not st.hiddenLock and st.character and st.dist then
			if st.dist < cfg.ContactRange then
				self.nextAttack = now + cfg.AttackCooldown
				self.round:grab(player, st, self)
				return
			end
		end
	end
end

--- Being lit up costs you something: it turns solid *and* angry.
function Entity:updateReveal(now)
	local revealed = now < self.revealedUntil
	if revealed == self.revealed then
		return
	end
	self.revealed = revealed
	local transparency = revealed and cfg.RevealTransparency or cfg.FadeTransparency
	for _, part in ipairs(self.parts) do
		part.Transparency = transparency
	end
	for _, part in ipairs(self.glowParts) do
		part.Transparency = revealed and 0 or 0.12
	end
	self.eyeLight.Brightness = revealed and 1.5 or 0.65
	if self.model then
		self.model:SetAttribute("Revealed", revealed)
		self.model:SetAttribute("Alpha", transparency)
	end
end

--- It must never leave the playable grid, or a player could outrun it onto the dock.
function Entity:keepInside()
	local level = self.level
	local limitX = level.halfW - self.tile / 2
	local limitZ = level.halfH - self.tile / 2
	local x, z = self.pos.X, self.pos.Z
	local moved = false

	if x < -limitX then
		x, moved = -limitX, true
	elseif x > limitX then
		x, moved = limitX, true
	end
	if z < -limitZ then
		z, moved = -limitZ, true
	elseif z > limitZ then
		z, moved = limitZ, true
	end

	if moved then
		self.pos = Vector3.new(x, 0, z)
		local gx, gy = self.level:tileOf(self.pos)
		if self.maze:walkable(gx, gy) then
			self.tx, self.ty = gx, gy
		end
		self.field = nil
		self.nextTile = nil
		self.repathIn = 0
	end
end

--- Blink into a distant corridor: punishment for it standing around uselessly, and
--- the round-start beat that keeps it out of the players' face.
function Entity:reposition(minTiles)
	local gx, gy = self:pickFarTile(minTiles or 14, { self.tx, self.ty })
	self:setPositionFromTile(gx, gy)
	self.patrolTile = { gx, gy }
	self.goal = { gx, gy }
	self.round:scare(1.2, "blink")
end

function Entity:beginFeed()
	self:setState("feeding")
	self.feedingUntil = self.time + 1.7
	self.targetPlayer = nil
	self.lastKnown = nil
	self.investigateTile = nil
	self.field = nil
	self.fieldKey = nil
	self.nextTile = nil
	self.speed = 0
end

--- Settle back down once the round's dirty business is over.
function Entity:settle()
	self:setState("patrol")
	self.feedingUntil = 0
	self.nextAttack = 0
	self.idleTime = 0
	self.aggro = 0
end

--- The gate is open. Stop letting the team stroll up to it.
function Entity:enroll()
	self:setState("investigate")
	self.investigateTile = { self.maze.entryX + 1, self.maze.entryY }
	self.investigateUntil = self.time + 30
	self.aggro = self.aggro + 1.6
	self.patrolTile = nil
	self.field = nil
	self.fieldKey = nil
	self.nextTile = nil
end

return Entity
