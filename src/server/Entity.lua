local Config = require(shared:WaitForChild("Config"))
local Util = require(shared:WaitForChild("Util"))

local Entity = {}
Entity.__index = Entity

local cfg = Config.Entity
local COS_HALF_FOV = math.cos(math.rad(cfg.FaceAngle / 2))
local DecisionRate = 1 / 20 -- perception + routing; motion runs every Heartbeat

