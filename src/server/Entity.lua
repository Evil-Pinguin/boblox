--- One pass over the live players: fills st.dist, st.seen, st.dread.
function Entity:scan()
	local now = self.time
	local radius = cfg.SightRange
	local best, bestScore
	self.closestDist = math.huge

	for player, st in self.round:eachPlayer() do
		st.seen = false
		st.dist = nil
		if st.joined and st.alive and not st.escaped and st.character and st.character.Parent then
			local to = st.pos - self.pos
			local flat = Vector3.new(to.X, 0, to.Z)
			local dist = flat.Magnitude
			st.dist = dist
			if dist < self.closestDist then
				self.closestDist = dist
			end

			local throughWall = dist < cfg.CloseSenseRange
			local clear = throughWall or self.maze:lineOfSight(self.tx, self.ty, st.tx, st.ty)

			if st.hiddenLock then
				-- Only a Hollow that is already hunting you, standing at the door,
				-- can pull you out. Otherwise you are simply not there.
				if self.state == "hunt" and self.targetPlayer == player and dist < cfg.KickRange then
					st.atDoor = true
				else
					st.atDoor = false
				end
			elseif clear then
				local facing = throughWall
				if not facing and dist > 0.01 then
					facing = self.dir:Dot(flat.Unit) > COS_HALF_FOV
				end
				-- Your beam is a searchlight. Catching sight of it means it sees you.
				local beamed = false
				if st.flashOn and st.look and dist < 120 and dist > 0.01 then
					beamed = st.look:Dot(-flat.Unit) > 0.9
				end
				if facing or beamed then
					st.seen = true
					st.atDoor = false
					if beamed then
						self.revealedUntil = now + cfg.RevealHold
						self.round:revealFlash(player)
					end
					local score = 1 - dist / radius + (beamed and 0.35 or 0)
					if score > (bestScore or -1) then
						best, bestScore = player, score
					end
				end
			else
				st.atDoor = false
			end
		end
	end

	return best
end

--- The single 0..1 number that drives the client's vignette, blur and shake.
function Entity:computeDread()
	local dreadBase = 0
	local closest = self.closestDist or math.huge
	if closest < math.huge then
		dreadBase = 1 - Util.clamp(closest / Config.Dread.Radius, 0, 1)
	end
	local stateWeight
	if self.state == "hunt" or self.state == "feeding" then
		stateWeight = Config.Dread.HuntMult
	elseif self.state == "investigate" then
		stateWeight = Config.Dread.InvestigateMult
	elseif self.state == "patrol" then
		stateWeight = Config.Dread.PatrolMult
	else
		stateWeight = 0.1
	end

	for player, st in self.round:eachPlayer() do
		local personal = 0
		if st.dist then
			personal = 1 - Util.clamp(st.dist / Config.Dread.Radius, 0, 1)
		end
		local dread = Util.clamp(personal * Config.Dread.ProximityFalloff + personal * 0.45 * stateWeight, 0, 1)
		if st.hiddenLock then
			dread = Util.clamp(dread + 0.3, 0, 1)
		end
		if self.state == "hunt" and self.targetPlayer == player then
			dread = 1
		end
		st.dread = dread
	end
end

function Entity:setState(nextState)
	if self.state == nextState then
		return
	end
	self.state = nextState
	if self.model then
		self.model:SetAttribute("State", nextState)
	end
end

--- A noise happened at `pos`. Loud enough and it is worth walking over to.
function Entity:hear(pos, radius)
	if self.state == "dormant" or self.state == "feeding" then
		return
	end
	if (pos - self.pos).Magnitude > radius then
		return
	end

	local gx, gy = self.level:tileOf(pos)
	gx, gy = self.round:nearestWalkable(self.maze, gx, gy)
	self.investigateTile = { gx, gy }
	self.investigateUntil = self.time + cfg.InvestigateTime
	if self.state ~= "hunt" then
		self:setState("investigate")
		self.field = nil
		self.nextTile = nil
		self.repathIn = 0
	end
end

