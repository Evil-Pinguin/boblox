--[[
	Entity - "the Hollow".

	A stalking AI with an explicit state machine and grid-accurate pathing. No
	PathfindingService and no baked navmesh: the maze is generated by us, so a BFS
	flow field is exact, costs about half a millisecond (measured in
	tools/test_maze.py), and cannot desync from the geometry.

	States
		dormant     never moves. Used for the round intro beat.
		patrol      drifts toward a deep tile, so the map is never safe.
		investigate walked to a noise, looks around, gives up.
		hunt        has you. Chases, with memory of the last confirmed position.
		feeding     mid-grab; deaf to everything else for a moment.

	Detection is generous about sound and strict about sight, which teaches the two
	rules the whole game runs on: move quietly, and never shine your beam at it.
]]

--[[ Shared modules live in ReplicatedStorage.Blacksite. Addressed through the service rather
     than script.Parent.Parent, because these folders are siblings, not ancestors. ]]
